var enquiryForm = document.getElementById('enquiry-form');
if (enquiryForm) {
    enquiryForm.addEventListener('submit', function (e) {
        e.preventDefault();
        var name = document.getElementById('name').value.trim();
        var surname = document.getElementById('surname').value.trim();
        var email = document.getElementById('email').value.trim();
        var service = document.getElementById('service').value;
        var message = document.getElementById('message').value.trim();
        var response = document.getElementById('form-response');
        var valid = true;
        showError('name-error', '');
        showError('surname-error', '');
        showError('email-error', '');
        showError('service-error', '');
        showError('message-error', '');
        response.textContent = '';
        response.className = 'form-response';
        if (name === '') {
            showError('name-error', 'Please enter your name.');
            valid = false;
        }
        if (surname === '') {
            showError('surname-error', 'Please enter your surname.');
            valid = false;
        }
        if (!isValidEmail(email)) {
            showError('email-error', 'Please enter a valid email address.');
            valid = false;
        }
        if (service === '') {
            showError('service-error', 'Please choose a type of shoot.');
            valid = false;
        }
        if (message.length < 10) {
            showError('message-error', 'Message must be at least 10 characters.');
            valid = false;
        }
        if (!valid) {
            response.textContent = 'Please fix the errors above.';
            response.classList.add('fail');
            return;
        }
        response.textContent = 'Sending...';
        setTimeout(function () {
            response.textContent = 'Thank you ' + name + '! Your enquiry has been received. We will reply within 48 hours.';
            response.classList.add('success');
            enquiryForm.reset();
        }, 1000);
    });
}
var contactForm = document.getElementById('contact-form');
if (contactForm) {
    contactForm.addEventListener('submit', function (e) {
        e.preventDefault();
        var name = document.getElementById('c-name').value.trim();
        var email = document.getElementById('c-email').value.trim();
        var phone = document.getElementById('c-phone').value.trim();
        var type = document.getElementById('c-type').value;
        var message = document.getElementById('c-message').value.trim();
        var valid = true;
        showError('c-name-error', '');
        showError('c-email-error', '');
        showError('c-phone-error', '');
        showError('c-type-error', '');
        showError('c-message-error', '');
        if (name === '') {
            showError('c-name-error', 'Please enter your name.');
            valid = false;
        }
        if (!isValidEmail(email)) {
            showError('c-email-error', 'Please enter a valid email address.');
            valid = false;
        }
        if (!/^[0-9+\s()-]{9,15}$/.test(phone)) {
            showError('c-phone-error', 'Please enter a valid phone number.');
            valid = false;
        }
        if (type === '') {
            showError('c-type-error', 'Please choose a message type.');
            valid = false;
        }
        if (message === '') {
            showError('c-message-error', 'Please write a message.');
            valid = false;
        }

        if (!valid) {
            return;
        }
        var subject = type + ' - ' + name;
        var body = 'Name: ' + name + '\n' +
                   'Email: ' + email + '\n' +
                   'Phone: ' + phone + '\n\n' +
                   message;
        window.location.href = 'mailto:empdStudio@gmail.com' +
            '?subject=' + encodeURIComponent(subject) +
            '&body=' + encodeURIComponent(body);
    });
}
