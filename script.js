var filterButtons = document.querySelectorAll('.filter-btn');
var gallerySearch = document.getElementById('gallery-search');
var figures = document.querySelectorAll('.gallery-grid figure');
var currentFilter = 'all';
function updateGallery() {
    var term = gallerySearch ? gallerySearch.value.toLowerCase().trim() : '';
    var shown = 0;
    figures.forEach(function (fig) {
        var category = fig.dataset.category;
        var altText = fig.querySelector('img').alt.toLowerCase();
        var matchesCategory = currentFilter === 'all' || category === currentFilter;
        var matchesSearch = term === '' || altText.indexOf(term) !== -1 || category.indexOf(term) !== -1;
        if (matchesCategory && matchesSearch) {
            fig.hidden = false;
            shown++;
        } else {
            fig.hidden = true;
        }
    });
    var noResults = document.getElementById('no-results');
    if (noResults) {
        noResults.hidden = shown > 0;
    }
}
filterButtons.forEach(function (btn) {
    btn.addEventListener('click', function () {
        filterButtons.forEach(function (b) {
            b.classList.remove('active');
        });
        btn.classList.add('active');
        currentFilter = btn.dataset.filter;
        updateGallery();
    });
});
if (gallerySearch) {
    gallerySearch.addEventListener('input', updateGallery);
}
